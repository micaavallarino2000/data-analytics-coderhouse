   -- Tabla CLIENTES
CREATE TABLE clientes (
    ID_Cliente      VARCHAR(10)     NOT NULL PRIMARY KEY,
    Nombre          VARCHAR(100)    NOT NULL,
    Apellido        VARCHAR(100)    NOT NULL,
    Email           VARCHAR(150)    NULL,
    Fecha_Registro  DATE            NOT NULL,
    Region          VARCHAR(100)    NOT NULL
    )

    -- Tabla PRODUCTOS
CREATE TABLE productos (
    ID_Producto     VARCHAR(10)     NOT NULL PRIMARY KEY,
    Nombre_producto VARCHAR(100)    NOT NULL,
    Categoria       VARCHAR(50)     NOT NULL,
    Precio_Unitario DECIMAL(10,2)   NOT NULL,
    Stock           VARCHAR(10)     NOT NULL
) 

-- Tabla VENTAS
CREATE TABLE ventas (
    ID_Venta    VARCHAR(15)     NOT NULL, 
    Fecha       DATE            NOT NULL,
    ID_Cliente  VARCHAR(10)     NOT NULL,
    ID_Producto VARCHAR(10)     NOT NULL,
    Cantidad    INT             NULL,
    Metodo_Pago VARCHAR(30)     NOT NULL,
    Estado      VARCHAR (100)   NULL,
    Total       DECIMAL (12,2)  NULL,
    
    CONSTRAINT FK_Ventas_Clientes FOREIGN KEY (ID_Cliente) REFERENCES clientes(ID_Cliente),
    CONSTRAINT FK_Ventas_Productos FOREIGN KEY (ID_Producto) REFERENCES productos(ID_Producto)
    )

    GO

    

